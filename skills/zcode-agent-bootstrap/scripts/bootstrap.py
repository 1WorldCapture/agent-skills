def append_board_prompt(root: Path, report: Report) -> None:
    path = root / "ROUTINES/task-prompts.md"
    marker = "## Vercel Board triage"
    if not path.exists():
        report.conflicts.append("ROUTINES/task-prompts.md (missing; prompt not appended)")
        return
    text = path.read_text(encoding="utf-8", errors="replace")
    if marker in text:
        report.skipped.append("ROUTINES/task-prompts.md (Board prompt already present)")
        return
    if MARKER not in text:
        report.conflicts.append("ROUTINES/task-prompts.md (user file exists; prompt not appended)")
        return
    addition = "\n\n" + marker + "\n\nSee `ROUTINES/vercel-board-triage.md`; use its copy-ready prompt and active Harness schedule.\n"
    if not getattr(report, "dry_run", False):
        path.write_text(text.rstrip() + addition, encoding="utf-8")
    report.created.append("ROUTINES/task-prompts.md (Board prompt)" + (" [dry-run]" if getattr(report, "dry_run", False) else ""))

def install_board_skill(root: Path, args: argparse.Namespace, report: Report) -> bool:
    skill_paths = [root / ".agents/skills/board/SKILL.md", root / ".zcode/skills/board/SKILL.md"]
    for skill_path in skill_paths:
        if skill_path.is_file():
            report.skipped.append(str(skill_path.parent.relative_to(root)) + "/ (Board skill already present)")
            return True
    command = ["npx", "--yes", "skills", "add", "vercel/board", "--skill", "board", "--yes"]
    if args.skip_board_install:
        report.warnings.append("Board skill installation skipped by --skip-board-install")
        return False
    if args.dry_run:
        report.created.append("run: " + " ".join(command) + " [dry-run]")
        return True
    try:
        completed = subprocess.run(command, cwd=root, capture_output=True, text=True, timeout=args.board_install_timeout)
    except (OSError, subprocess.SubprocessError) as exc:
        report.errors.append("Board skill install failed: " + str(exc))
        return False
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "").strip().replace("\n", " ")[:300]
        report.errors.append("Board skill install failed (exit " + str(completed.returncode) + ")" + ((": " + detail) if detail else ""))
        return False
    installed_path = next((path for path in skill_paths if path.is_file()), None)
    if installed_path is None:
        report.errors.append("Board skill installer completed but no project Board SKILL.md was found")
        return False
    report.created.append(str(installed_path.parent.relative_to(root)) + "/ (installed by skills CLI)")
    return True

def board_init(root: Path, args: argparse.Namespace, report: Report) -> None:
    report.dry_run = args.dry_run
    if not ensure_baseline(root, report):
        return
    if not args.non_interactive and not sys.stdin.isatty():
        report.errors.append("board-init needs an interactive terminal; pass --non-interactive with --board-profile and other values")
        return
    config = board_config(args, root, report)
    if config is None or report.errors:
        return
    installed = install_board_skill(root, args, report)
    if not installed and not args.skip_board_install:
        return
    integration_dir = root / "INTEGRATIONS"
    config_path = integration_dir / "VERCEL_BOARD.md"
    routine_path = root / "ROUTINES/vercel-board-triage.md"
    if integration_dir.exists() and not integration_dir.is_dir():
        report.conflicts.append("INTEGRATIONS (expected directory)")
        return
    elif not integration_dir.exists():
        if args.dry_run:
            report.created.append("INTEGRATIONS/ [dry-run]")
        else:
            integration_dir.mkdir(parents=True, exist_ok=False)
            report.created.append("INTEGRATIONS/")
    for path, content in ((config_path, board_config_text(config)), (routine_path, board_routine_text(config))):
        rel = str(path.relative_to(root))
        if path.exists():
            if path.is_file() and BOARD_MARKER in path.read_text(encoding="utf-8", errors="replace"):
                report.skipped.append(rel + " (managed file exists; preserved)")
            else:
                report.conflicts.append(rel + " (user file exists; preserved)")
            continue
        if args.dry_run:
            report.created.append(rel + " [dry-run]")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            report.created.append(rel)
    append_board_prompt(root, report)
    zcode_root = root / ".zcode/skills"
    zcode_skill = zcode_root / "board"
    if zcode_root.is_dir() and (root / ".agents/skills/board").is_dir():
        if zcode_skill.exists():
            report.skipped.append(".zcode/skills/board/ (existing Zcode adapter preserved)")
        elif args.dry_run:
            report.warnings.append(".zcode/skills exists; copy .agents/skills/board/ there if this Zcode build does not discover .agents/skills")
        else:
            shutil.copytree(root / ".agents/skills/board", zcode_skill)
            report.created.append(".zcode/skills/board/ (Zcode compatibility copy)")

def current_root(value: str) -> Path:
    root = Path(value).expanduser().resolve()
    cwd = Path.cwd().resolve()
    if root != cwd:
        raise ValueError("root must equal the current working directory")
    if root == Path(root.anchor):
        raise ValueError("refusing to scaffold a filesystem root")
    return root

