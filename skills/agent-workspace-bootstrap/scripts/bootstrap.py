def write_scaffold(root: Path, files: dict[str, str], extra_dirs: list[str], args: argparse.Namespace, harnesses: list[str], report: Report) -> None:
    dirs: list[str] = []
    for rel in REQUIRED_DIRS + extra_dirs:
        if rel not in dirs:
            dirs.append(rel)
    for rel in dirs:
        path = root / rel
        if path.exists():
            if path.is_dir():
                report.skipped.append(rel + "/")
            else:
                report.conflicts.append(rel + " (expected directory)")
            continue
        if args.dry_run:
            report.created.append(rel + "/ [dry-run]")
        else:
            path.mkdir(parents=True, exist_ok=False)
            report.created.append(rel + "/")
    for rel, content in files.items():
        path = root / rel
        if path.exists():
            if path.is_file() and is_managed_text(path.read_text(encoding="utf-8", errors="replace")):
                report.skipped.append(rel + " (managed file exists; preserved)")
            else:
                report.conflicts.append(rel + " (user file exists; preserved)")
            continue
        if args.dry_run:
            report.created.append(rel + " [dry-run]")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            report.created.append(rel)
    state = root / ".agents/bootstrap-state.yaml"
    if not state.exists():
        if args.dry_run:
            report.created.append(".agents/bootstrap-state.yaml [dry-run]")
        else:
            state.write_text(state_text(root, args, files, harnesses), encoding="utf-8")
            report.created.append(".agents/bootstrap-state.yaml")
    else:
        report.skipped.append(".agents/bootstrap-state.yaml (preserved)")

def state_text(root: Path, args: argparse.Namespace, files: dict[str, str], harnesses: list[str]) -> str:
    harness_values = harnesses or ["portable"]
    lines = [
        "schema: " + SCHEMA,
        "agent_id: " + quote(slugify(args.agent_id or root.name)),
        "generated_at: " + quote(dt.datetime.now(dt.timezone.utc).isoformat()),
        "mode: " + quote(args.mode),
        "harnesses:",
        *("  - " + quote(h) for h in harness_values),
        "generated_files:",
    ]
    for rel in sorted(files):
        path = root / rel
        digest = hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else "pending"
        lines.append("  - path: " + quote(rel))
        lines.append("    sha256: " + quote(digest))
    return chr(10).join(lines) + chr(10)

def validate(root: Path, report: Report, harnesses: list[str] | None = None) -> None:
    harnesses = harnesses or []
    adapter_dirs, adapter_files = render_adapters(harnesses)
    required_dirs = list(REQUIRED_DIRS)
    for rel in adapter_dirs:
        if rel not in required_dirs:
            required_dirs.append(rel)
    required_files = list(REQUIRED_FILES)
    for rel in adapter_files:
        if rel not in required_files:
            required_files.append(rel)
    for rel in required_dirs:
        path = root / rel
        if not path.is_dir():
            report.errors.append("missing directory: " + rel)
    for rel in required_files:
        path = root / rel
        if not path.is_file():
            report.errors.append("missing file: " + rel)
    for rel in VALIDATED_TEXT_FILES:
        path = root / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if "{{" in text or "}}" in text:
            report.errors.append("unresolved template token: " + rel)
        for pattern in SECRET_PATTERNS:
            if pattern.search(text):
                report.errors.append("secret-like value detected in: " + rel)
                break
    cursor_rule = root / ".cursor/rules/agent-workspace.mdc"
    if cursor_rule.is_file():
        text = cursor_rule.read_text(encoding="utf-8", errors="replace")
        if not (text.startswith("---\n") and "\n---\n" in text[4:]):
            report.errors.append(".cursor/rules/agent-workspace.mdc missing YAML frontmatter")
        if "AGENTS.md" not in text:
            report.errors.append(".cursor/rules/agent-workspace.mdc must reference AGENTS.md")
    agents = root / "AGENTS.md"
    if agents.is_file():
        text = agents.read_text(encoding="utf-8", errors="replace")
        for token in ("FILESYSTEM.md", ".agents/skills", "MEMORY/daily", "ROUTINES", "LOGS"):
            if token not in text:
                report.errors.append("AGENTS.md startup protocol omits: " + token)
    manifest = root / "agent.yaml"
    if manifest.is_file():
        text = manifest.read_text(encoding="utf-8", errors="replace")
        for token in ("apiVersion:", "kind:", "metadata:", "spec:", "mission:", "portableEntryPoint:", "portableSkillsRoot:"):
            if token not in text:
                report.errors.append("agent.yaml missing key: " + token)
    if (root / "SKILLS").exists():
        report.warnings.append("legacy SKILLS/ detected; use .agents/skills/ as the portable skill root")
    if (root / ".agent").exists():
        report.warnings.append("legacy .agent/ detected; use .agents/ for shared Harness metadata")

def status(root: Path, report: Report) -> None:
    for rel in REQUIRED_FILES:
        if (root / rel).is_file():
            report.skipped.append(rel)
        else:
            report.warnings.append("missing: " + rel)
    if (root / ".agents/bootstrap-state.yaml").is_file():
        report.skipped.append("bootstrap state present")
    else:
        report.warnings.append("bootstrap state missing")
    if (root / ".cursor/rules/agent-workspace.mdc").is_file() or (root / ".cursor/skills").is_dir():
        report.skipped.append("Cursor adapter present")
    if (root / ".zcode/skills").is_dir():
        report.skipped.append("Zcode adapter present")
    if (root / "SKILLS").exists():
        report.warnings.append("legacy SKILLS/ present")
    if (root / ".agent").exists():
        report.warnings.append("legacy .agent/ present")
    if (root / "INTEGRATIONS/VERCEL_BOARD.md").is_file():
        report.skipped.append("INTEGRATIONS/VERCEL_BOARD.md (Board integration present)")
    if (
        (root / ".agents/skills/board/SKILL.md").is_file()
        or (root / ".cursor/skills/board/SKILL.md").is_file()
        or (root / ".zcode/skills/board/SKILL.md").is_file()
    ):
        report.skipped.append("Board Skill present")

def print_report(report: Report, mode: str, as_json: bool) -> int:
    payload = report.as_dict()
    if as_json:
        print(json.dumps({"mode": mode, **payload}, indent=2, ensure_ascii=False))
    else:
        print("mode: " + mode)
        for key in ("created", "skipped", "conflicts", "warnings", "errors"):
            values = payload[key]
            print(key + ": " + str(len(values)))
            for value in values:
                print("  - " + value)
    return 1 if report.errors else 0

def main() -> int:
    parser = argparse.ArgumentParser(description="Scaffold and validate a cross-Harness Agent Project.")
    parser.add_argument("--root", default=".")
    parser.add_argument("--mode", choices=("bootstrap", "repair", "validate", "status", "board-init"), default="bootstrap")
    parser.add_argument("--harness", default="portable", help="Harness adapters to scaffold or validate: portable (default) or comma-separated adapters (cursor, zcode)")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--agent-id")
    parser.add_argument("--name")
    parser.add_argument("--role")
    parser.add_argument("--mission")
    parser.add_argument("--language")
    parser.add_argument("--timezone")
    parser.add_argument("--model")
    parser.add_argument("--tools", default="")
    parser.add_argument("--skills", default="")
    parser.add_argument("--non-interactive", action="store_true", help="skip the Bootstrap Wizard; requires all mandatory bootstrap flags")
    parser.add_argument("--board-hosting", choices=("self-hosted", "vercel"), default="self-hosted", help="where the Board runs: vb serve (default) or Vercel's API")
    parser.add_argument("--board-cli", help="Board client command (default vb, or 'vercel board' with --board-hosting vercel)")
    parser.add_argument("--board-url")
    parser.add_argument("--board-scope")
    parser.add_argument("--board-name")
    parser.add_argument("--board-profile")
    parser.add_argument("--board-channels", default="")
    parser.add_argument("--skip-board-install", action="store_true")
    parser.add_argument("--board-install-timeout", type=int, default=180)
    args = parser.parse_args()
    report = Report()
    try:
        root = current_root(args.root)
    except ValueError as exc:
        report.errors.append(str(exc))
        return print_report(report, args.mode, args.json)
    harnesses = parse_harnesses(args.harness, report)
    if harnesses is None:
        return print_report(report, args.mode, args.json)
    try:
        if args.mode == "board-init":
            board_init(root, args, harnesses, report)
            return print_report(report, args.mode, args.json)
        if args.mode == "bootstrap" and not bootstrap_wizard(args, root, report):
            return print_report(report, args.mode, args.json)
        if args.mode == "bootstrap":
            harnesses = parse_harnesses(args.harness, report)
            if harnesses is None:
                return print_report(report, args.mode, args.json)
    except EOFError:
        report.errors.append(
            "bootstrap wizard ended before confirmation; provide the mandatory values or pass --non-interactive"
        )
        return print_report(report, args.mode, args.json)
    files = render(args, root)
    extra_dirs, adapter_files = render_adapters(harnesses)
    all_files = {**files, **adapter_files}
    if args.mode in ("bootstrap", "repair"):
        write_scaffold(root, all_files, extra_dirs, args, harnesses, report)
        if args.mode == "bootstrap" and not args.dry_run:
            validate(root, report, harnesses)
    elif args.mode == "validate":
        validate(root, report, harnesses)
    else:
        status(root, report)
    return print_report(report, args.mode, args.json)

